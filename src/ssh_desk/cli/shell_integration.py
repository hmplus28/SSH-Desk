"""OS-level CLI integration: command-name symlinks, bash/zsh completions."""

import logging
import os
import re
from pathlib import Path

from ssh_desk.core.constants import RESERVED_CLI_NAMES
from ssh_desk.core.exceptions import ValidationErrorX

log = logging.getLogger("ssh_desk.shell_integration")

NAME_RE = re.compile(r"^[a-z][a-z0-9_-]{0,31}$")


def bin_dir() -> Path:
    return Path(os.environ.get("SSH_DESK_BIN_DIR", Path.home() / ".local" / "bin"))


def cli_script_path() -> Path:
    """Path of a runnable CLI entry: console script, wrapper, or interpreter -m."""
    from shutil import which

    found = which("ssh-desk-cli")
    if found:
        return Path(found)
    wrapper = Path(os.environ.get("SSH_DESK_DATA_DIR", Path.home() / ".local" / "share" / "ssh-desk")) / "bin" / "ssh-desk-cli"
    if wrapper.exists():
        return wrapper
    return Path(sys_executable())  # fallback: caller should use python -m


def sys_executable() -> str:
    import sys

    return sys.executable


def _ensure_symlink(link: Path, target: Path) -> None:
    link.parent.mkdir(parents=True, exist_ok=True)
    if link.is_symlink() or link.exists():
        if link.is_symlink() and link.resolve() == target.resolve():
            return
        link.unlink()
    link.symlink_to(target)


def install_cli_name(name: str, previous: str = "") -> Path:
    """Create ~/.local/bin/<name> -> CLI entry. Removes the previous name symlink."""
    if not NAME_RE.match(name):
        raise ValidationErrorX(
            f"Invalid CLI command name '{name}'. Use 1-32 chars: lowercase letters, digits, '-' or '_'."
        )
    if name in RESERVED_CLI_NAMES:
        raise ValidationErrorX(f"'{name}' is a reserved system command name; choose another.")
    target = cli_script_path()
    bindir = bin_dir()
    bindir.mkdir(parents=True, exist_ok=True)
    link = bindir / name
    _ensure_symlink(link, target)
    if previous and previous != name:
        old = bindir / previous
        try:
            if old.is_symlink():
                old.unlink()
        except OSError:
            pass
    _ensure_symlink(bindir / "ssh-desk-cli", target)
    log.info("CLI command installed: %s -> %s", link, target)
    return link


def bash_completion_script(command: str) -> str:
    return f"""# bash completion for {command} (generated by SSH Desk)
_{command}_completions() {{
    local cur prev
    cur="${{COMP_WORDS[COMP_CWORD]}}"
    prev="${{COMP_WORDS[COMP_CWORD-1]}}"
    local candidates
    candidates=$("{command}" __complete "$cur" "$COMP_LINE" 2>/dev/null)
    COMPREPLY=( $(compgen -W "$candidates" -- "$cur") )
}}
complete -o default -F _{command}_completions {command}
"""


def zsh_completion_script(command: str) -> str:
    return f"""#compdef {command}
# zsh completion for {command} (generated by SSH Desk)
_{command}() {{
    local -a candidates
    candidates=($({command} __complete "" "$BUFFER" 2>/dev/null))
    _describe 'command' candidates
}}
_{command} "$@"
"""


def completion_file_path(shell: str, command: str) -> Path:
    if shell == "bash":
        return Path.home() / ".local" / "share" / "bash-completion" / "completions" / command
    return Path(os.environ.get("SSH_DESK_DATA_DIR", Path.home() / ".local" / "share" / "ssh-desk")) / "completions" / f"_{command}"


def install_completions(shell: str, command: str) -> Path:
    path = completion_file_path(shell, command)
    path.parent.mkdir(parents=True, exist_ok=True)
    script = bash_completion_script(command) if shell == "bash" else zsh_completion_script(command)
    path.write_text(script)
    return path
